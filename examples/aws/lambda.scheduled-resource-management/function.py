def _process_units(units: list[dict[str, Any]]) -> list[dict[str, Any]]:
    if not units:
        return []
    with ThreadPoolExecutor(max_workers=10) as pool:
        per_unit = list(pool.map(_process_unit, units))
    return [result for unit_results in per_unit for result in unit_results]


def _process_unit(unit: dict[str, Any]) -> list[dict[str, Any]]:
    resources = unit.get('resources', [])
    if not resources:
        return []
    try:
        levels = _topo_levels(resources)
    except ValueError as e:
        return [{**r, 'status': 'error', 'message': f'invalid dependency set: {e}'} for r in resources]

    action = resources[0].get('action', 'start')
    if action == 'stop':
        levels.reverse()

    results: list[dict[str, Any]] = []
    upstream_not_stopped = False
    for index, level in enumerate(levels):
        if upstream_not_stopped:
            results.extend(
                {**r, 'status': 'error', 'message': 'skipped: upstream resources not confirmed stopped'}
                for r in level
            )
            continue

        level_results = [_process_one(r) for r in level]
        results.extend(level_results)

        if action == 'stop':
            for resource, result in zip(level, level_results):
                if result.get('status') == 'ok':
                    _set_alarm_actions(resource, result, enabled=False)

        is_final = index == len(levels) - 1

        if is_final:
            if action == 'start':
                for resource, result in zip(level, level_results):
                    if result.get('status') == 'ok':
                        _set_alarm_actions(resource, result, enabled=True)
            continue

        for resource, result in zip(level, level_results):
            failed_call = result.get('status') != 'ok'
            excluded = result.get('message', '').startswith('excluded:')
            if action == 'stop':
                if failed_call or excluded:
                    upstream_not_stopped = True
                elif not _wait_stopped(resource):
                    result['status'] = 'error'
                    result['message'] = f"{result.get('message', '')}; not confirmed stopped within {STOP_WAIT_MAX_SECONDS}s"
                    upstream_not_stopped = True
            else:
                if not failed_call and not _wait_ready(resource):
                    result['status'] = 'error'
                    result['message'] = f"{result.get('message', '')}; not ready within {START_WAIT_MAX_SECONDS}s (dependents started anyway)"
                if not failed_call:
                    _set_alarm_actions(resource, result, enabled=True)
    return results


def _process_one(resource: dict[str, Any]) -> dict[str, Any]:
    rtype = resource.get('type')
    action = resource.get('action', 'start')
    source = resource.get('source')
    try:
        if rtype == 'ec2':
            return _stop_ec2(resource['id'], source=source) if action == 'stop' else _start_ec2(resource['id'], source=source)
        if rtype == 'rds':
            return _stop_rds(resource['id'], source=source) if action == 'stop' else _start_rds(resource['id'], source=source)
        if rtype == 'ecs':
            if action == 'stop':
                return _stop_ecs(resource['cluster'], resource['service'], source=source)
            return _start_ecs(resource['cluster'], resource['service'], resource.get('desiredCount', 1), source=source)
        if rtype == 'asg':
            if action == 'stop':
                return _stop_asg(resource['name'], source=source)
            return _start_asg(resource['name'], resource.get('desiredCapacity', 1), source=source)
        return {**resource, 'status': 'error', 'message': f'unknown type `{rtype}`'}
    except Exception as e:
        return {**resource, 'status': 'error', 'message': str(e)}


def _check_environment(tags: list[dict[str, str]]) -> str | None:
    env = next((t['Value'] for t in tags if t.get('Key') == 'Environment'), None)
    if env is None:
        return 'refused: no Environment tag'
    if env == 'Production':
        return 'refused: production'
    return None


def _check_exclude(tags: list[dict[str, str]], source: str | None) -> str | None:
    if source != 'scheduler':
        return None
    value = next((t['Value'] for t in tags if t.get('Key') == EXCLUDE_TAG_KEY), None)
    if value == 'true':
        return f'excluded: {EXCLUDE_TAG_KEY}'
    return None


