"""
Scheduled Resource Controller

On-demand Lambda for starting and stopping non-production AWS resources (EC2, RDS, ECS, ASG).
See README.md for the full specification.

Routes:
- POST /slack/start, /slack/stop for Slack slash commands (HMAC-verified, channel-allowlisted)
- POST /api/iam/start, /api/iam/stop for IAM-authenticated HTTP (SigV4 at API Gateway)
- EventBridge Scheduler direct invoke {action, source: 'scheduler'}

Implementation notes
--------------------
Every request expands to *units* (one alias = one unit; all inline scheduler specs = one unit; one Slack/IAM body = one
unit). Units run in parallel. Within a unit, `dependsOn` references create topological levels processed sequentially.

`RESOURCE_REGISTRY` maps token-grammar keys to specs with optional `dependsOn`.
Aliases and scheduler targets list leaf resources. Dependencies are auto-included from the registry. Inline/alias specs
win on deduplication, with the registry merging its `dependsOn` onto existing specs.

Check readiness using boto3 waiters where AWS provides them (`db_instance_available`, `services_stable`,
`instance_running`, `instance_stopped`), fallback to bounded polling where it does not (autoscaling has no waiters;
RDS has no `stopped` waiter).

Slack's synchronous handler verifies the signature and returns a 200 within 3s, then self-invokes asynchronously
(InvocationType='Event') for the actual work. The async continuation posts results to Slack via `response_url`.

One paginated `describe_alarms` call per invocation builds a dimension-value-to-alarm-names map. Client-side filtering
is required (DescribeAlarms has no server-side dimension filter).
Alarm-level exclusion tags are fetched via `resourcegroupstaggingapi.get_resources` at index build time.
"""

