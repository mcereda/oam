def _start_ec2(instance_id: str, *, source: str | None = None) -> dict[str, Any]:
    desc = _ec2.describe_instances(InstanceIds=[instance_id])
    reservations = desc.get('Reservations', [])
    if not reservations or not reservations[0].get('Instances'):
        return {'type': 'ec2', 'id': instance_id, 'status': 'error', 'message': 'not found'}
    inst = reservations[0]['Instances'][0]
    arn = f"arn:aws:ec2:{REGION}:{reservations[0]['OwnerId']}:instance/{instance_id}"
    tags = inst.get('Tags', [])
    rejection = _check_environment(tags)
    if rejection:
        return {'type': 'ec2', 'id': instance_id, 'arn': arn, 'status': 'error', 'message': rejection}
    state = inst.get('State', {}).get('Name')
    if state in ('running', 'pending'):
        result = {'type': 'ec2', 'id': instance_id, 'arn': arn, 'status': 'ok', 'message': f'already {state}'}
    else:
        _ec2.start_instances(InstanceIds=[instance_id])
        result = {'type': 'ec2', 'id': instance_id, 'arn': arn, 'status': 'ok', 'message': 'started'}
    if _check_exclude(tags, source):
        result['alarmExcluded'] = True
    return result


def _start_rds(db_id: str, *, source: str | None = None) -> dict[str, Any]:
    desc = _rds.describe_db_instances(DBInstanceIdentifier=db_id)
    instances = desc.get('DBInstances', [])
    if not instances:
        return {'type': 'rds', 'id': db_id, 'status': 'error', 'message': 'not found'}
    inst = instances[0]
    arn = inst['DBInstanceArn']
    tags = _rds.list_tags_for_resource(ResourceName=arn).get('TagList', [])
    rejection = _check_environment(tags)
    if rejection:
        return {'type': 'rds', 'id': db_id, 'arn': arn, 'status': 'error', 'message': rejection}
    state = inst.get('DBInstanceStatus')
    if state in ('available', 'starting', 'configuring-enhanced-monitoring'):
        result = {'type': 'rds', 'id': db_id, 'arn': arn, 'status': 'ok', 'message': f'already {state}'}
    else:
        _rds.start_db_instance(DBInstanceIdentifier=db_id)
        result = {'type': 'rds', 'id': db_id, 'arn': arn, 'status': 'ok', 'message': 'started'}
    if _check_exclude(tags, source):
        result['alarmExcluded'] = True
    return result


def _start_ecs(cluster: str, service: str, desired_count: int, *, source: str | None = None) -> dict[str, Any]:
    desc = _ecs.describe_services(cluster=cluster, services=[service], include=['TAGS'])
    services = desc.get('services', [])
    if not services:
        return {'type': 'ecs', 'cluster': cluster, 'service': service, 'status': 'error', 'message': 'not found'}
    svc = services[0]
    arn = svc['serviceArn']
    # ECS tags use lowercase key/value; normalize for _check_environment.
    normalized_tags = [{'Key': t['key'], 'Value': t['value']} for t in svc.get('tags', [])]
    rejection = _check_environment(normalized_tags)
    if rejection:
        return {'type': 'ecs', 'cluster': cluster, 'service': service, 'arn': arn, 'status': 'error', 'message': rejection}
    current = svc.get('desiredCount', 0)
    if current >= desired_count:
        result = {'type': 'ecs', 'cluster': cluster, 'service': service, 'arn': arn, 'status': 'ok', 'message': f'already at desiredCount={current}'}
    else:
        _ecs.update_service(cluster=cluster, service=service, desiredCount=desired_count)
        result = {'type': 'ecs', 'cluster': cluster, 'service': service, 'arn': arn, 'status': 'ok', 'message': f'desiredCount {current} -> {desired_count}'}
    if _check_exclude(normalized_tags, source):
        result['alarmExcluded'] = True
    return result


def _start_asg(asg_name: str, desired_capacity: int, *, source: str | None = None) -> dict[str, Any]:
    desc = _asg.describe_auto_scaling_groups(AutoScalingGroupNames=[asg_name])
    groups = desc.get('AutoScalingGroups', [])
    if not groups:
        return {'type': 'asg', 'name': asg_name, 'status': 'error', 'message': 'not found'}
    group = groups[0]
    arn = group['AutoScalingGroupARN']
    tags = group.get('Tags', [])
    rejection = _check_environment(tags)
    if rejection:
        return {'type': 'asg', 'name': asg_name, 'arn': arn, 'status': 'error', 'message': rejection}
    current = group.get('DesiredCapacity', 0)
    current_min = group.get('MinSize', 0)
    needs_min_restore = current_min == 0
    if current >= desired_capacity and not needs_min_restore:
        result = {'type': 'asg', 'name': asg_name, 'arn': arn, 'status': 'ok', 'message': f'already at desiredCapacity={current}'}
    else:
        kwargs: dict = {'DesiredCapacity': desired_capacity}
        if needs_min_restore:
            kwargs['MinSize'] = 1
        _asg.update_auto_scaling_group(AutoScalingGroupName=asg_name, **kwargs)
        msg = f'desiredCapacity {current} -> {desired_capacity}'
        if needs_min_restore:
            msg += ', MinSize 0 -> 1'
        result = {'type': 'asg', 'name': asg_name, 'arn': arn, 'status': 'ok', 'message': msg}
    if _check_exclude(tags, source):
        result['alarmExcluded'] = True
    return result


